import { athletePhoto, flagUrl } from "@/lib/archive"
import { type Athlete, type AthleteDivision } from "@/data/types"

type DirectoryRow = {
  archiveId: number
  firstName: string
  lastName: string
  country: string
  countryCode: string
  gender: AthleteDivision
  activeYears: string
  intlContests: number | null
  intlWins: number | null
  worldApps: number | null
  worldWins: number
  height?: string
  weight?: string
  born?: string
  titles?: string[]
  bio?: string
  personalBests?: Athlete["personalBests"]
  slug?: string
  image?: string
}

function row(entry: DirectoryRow): Athlete {
  const name = `${entry.firstName} ${entry.lastName}`
  return {
    slug:
      entry.slug ??
      name
        .normalize("NFD")
        .replaceAll(/[\u0300-\u036f]/g, "")
        .toLowerCase()
        .replaceAll("æ", "ae")
        .replaceAll(/[^a-z0-9]+/g, "-")
        .replaceAll(/(^-|-$)/g, ""),
    archiveId: entry.archiveId,
    firstName: entry.firstName,
    lastName: entry.lastName,
    name,
    country: entry.country,
    countryCode: entry.countryCode,
    flagUrl: flagUrl(entry.country),
    titles: entry.titles ?? [],
    height: entry.height ?? "",
    weight: entry.weight ?? "",
    born: entry.born ?? "",
    image: entry.image ?? athletePhoto(entry.archiveId),
    bio:
      entry.bio ??
      `${name} (${entry.country}) is filed in the Strongman Archives directory with ${entry.intlContests ?? "—"} international contests across ${entry.activeYears}.`,
    personalBests: entry.personalBests ?? [],
    gender: entry.gender,
    activeYears: entry.activeYears,
    intlContests: entry.intlContests,
    intlWins: entry.intlWins,
    worldApps: entry.worldApps,
    worldWins: entry.worldWins,
  }
}

